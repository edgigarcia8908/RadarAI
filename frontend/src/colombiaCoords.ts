/** Distancia en km entre dos puntos (fórmula de Haversine). */
function distanciaKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 + Math.cos((lat1 * Math.PI) / 180) * Math.cos((lat2 * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

/** Dado lat/lng (ej. de navigator.geolocation), encuentra el municipio más cercano de todo el país. */
export function municipioMasCercano(lat: number, lng: number): { departamento: string; ciudad: string } | null {
  let mejor: { departamento: string; ciudad: string; dist: number } | null = null;
  for (const [departamento, ciudades] of Object.entries(COLOMBIA_LOCATIONS)) {
    for (const c of ciudades) {
      const dist = distanciaKm(lat, lng, c.lat, c.lng);
      if (!mejor || dist < mejor.dist) mejor = { departamento, ciudad: c.name, dist };
    }
  }
  return mejor ? { departamento: mejor.departamento, ciudad: mejor.ciudad } : null;
}
